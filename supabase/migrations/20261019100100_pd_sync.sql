-- Google Sheets replication for v2 (its own spreadsheet): lease + baseline snapshot, the conflict
-- log, and the change ping. Same engine as v1 (docs/SYNC.md), separate state so the two
-- spreadsheets never share a lease or a baseline. The engine writes with the service role.

create table public.pd_sync_state (
  id              boolean primary key default true,
  baseline        jsonb not null default '{}'::jsonb,
  initialized     boolean not null default false,
  lease_token     uuid,
  lease_until     timestamptz,
  last_success_at timestamptz,
  last_error      text,
  failures        integer not null default 0,
  last_ping_at    timestamptz,
  constraint pd_sync_state_singleton check (id),
  constraint pd_sync_state_failures_check check (failures >= 0)
);

insert into public.pd_sync_state (id) values (true);


create table public.pd_sync_conflicts (
  id          bigint generated by default as identity primary key,
  created_at  timestamptz not null default now(),
  table_name  text not null,
  row_key     text,
  column_name text,
  baseline    jsonb,
  sheet_value jsonb,
  db_value    jsonb,
  resolution  text,
  resolved_at timestamptz,
  resolved_by uuid references auth.users (id) on delete set null
);

create index pd_sync_conflicts_open_idx on public.pd_sync_conflicts (created_at desc) where resolved_at is null;
create index pd_sync_conflicts_resolved_by_idx on public.pd_sync_conflicts (resolved_by);

alter table public.pd_sync_state     enable row level security;
alter table public.pd_sync_conflicts enable row level security;

create policy pd_sync_state_admin_select on public.pd_sync_state
  as permissive for select to authenticated using ((select public.is_admin()));
create policy pd_sync_conflicts_admin_all on public.pd_sync_conflicts
  as permissive for all to authenticated
  using ((select public.is_admin())) with check ((select public.is_admin()));

revoke all on table public.pd_sync_state, public.pd_sync_conflicts from anon;
revoke insert, update, delete on table public.pd_sync_state from authenticated;
revoke truncate, references, trigger on table public.pd_sync_state, public.pd_sync_conflicts from authenticated;


-- ---------------------------------------------------------------- lease (service role only)
create or replace function public.pd_sync_claim_lease(p_ttl_seconds integer)
returns uuid
language plpgsql
set search_path = ''
as $$
declare
  v_token uuid;
begin
  if p_ttl_seconds is null or p_ttl_seconds < 1 or p_ttl_seconds > 900 then
    raise exception using errcode = '22023', message = 'invalid_input', detail = 'p_ttl_seconds (1..900)';
  end if;

  update public.pd_sync_state s
     set lease_token = pg_catalog.gen_random_uuid(),
         lease_until = pg_catalog.clock_timestamp() + pg_catalog.make_interval(secs => p_ttl_seconds)
   where s.id
     and (s.lease_until is null or s.lease_until <= pg_catalog.clock_timestamp())
  returning s.lease_token into v_token;

  return v_token;
end;
$$;

create or replace function public.pd_sync_release_lease(p_token uuid, p_baseline jsonb default null, p_error text default null)
returns boolean
language plpgsql
set search_path = ''
as $$
begin
  update public.pd_sync_state s
     set lease_token     = null,
         lease_until     = null,
         baseline        = coalesce(p_baseline, s.baseline),
         initialized     = s.initialized or (p_baseline is not null and p_error is null),
         last_success_at = case when p_error is null then pg_catalog.clock_timestamp() else s.last_success_at end,
         last_error      = p_error,
         failures        = case when p_error is null then 0 else s.failures + 1 end
   where s.id
     and p_token is not null
     and s.lease_token = p_token;

  return found;
end;
$$;

revoke all on function public.pd_sync_claim_lease(integer) from public, anon, authenticated;
revoke all on function public.pd_sync_release_lease(uuid, jsonb, text) from public, anon, authenticated;
grant execute on function public.pd_sync_claim_lease(integer) to service_role;
grant execute on function public.pd_sync_release_lease(uuid, jsonb, text) to service_role;


-- ---------------------------------------------------------------- change ping
-- After a change from the app, ask v2's /api/sync/run to run (debounced to one ping per 10 s).
-- Reads its own Vault secrets (pd_sync_run_url, pd_sync_secret), so v1's ping is unaffected.
-- Writes by the service role (the engine itself) never ping. Any failure is logged and ignored.
create or replace function private.pd_sync_ping()
returns trigger
language plpgsql
security definer
set search_path = ''
as $_$
declare
  v_url    text;
  v_secret text;
begin
  begin
    if coalesce(
         nullif(pg_catalog.current_setting('request.jwt.claim.role', true), ''),
         nullif(pg_catalog.current_setting('request.jwt.claims', true), '')::jsonb ->> 'role'
       ) = 'service_role' then
      return null;
    end if;

    if not exists (select 1 from pg_catalog.pg_extension e where e.extname = 'pg_net')
       or pg_catalog.to_regclass('vault.decrypted_secrets') is null then
      return null;
    end if;

    execute $q$
      select max(d.decrypted_secret) filter (where d.name = 'pd_sync_run_url'),
             max(d.decrypted_secret) filter (where d.name = 'pd_sync_secret')
        from vault.decrypted_secrets d
       where d.name in ('pd_sync_run_url', 'pd_sync_secret')
    $q$ into v_url, v_secret;

    if coalesce(v_url, '') = '' or coalesce(v_secret, '') = '' then
      return null;
    end if;

    perform 1
       from public.pd_sync_state s
      where s.id
        and (s.last_ping_at is null
             or s.last_ping_at < pg_catalog.clock_timestamp() - interval '10 seconds')
        for update skip locked;
    if not found then
      return null;
    end if;

    update public.pd_sync_state s
       set last_ping_at = pg_catalog.clock_timestamp()
     where s.id;

    execute $q$
      select net.http_post(
        url                  := $1,
        body                 := $2,
        headers              := $3,
        timeout_milliseconds := 5000
      )
    $q$
    using v_url,
          pg_catalog.jsonb_build_object('source', 'db', 'table', tg_table_name),
          pg_catalog.jsonb_build_object(
            'Content-Type',  'application/json',
            'Authorization', 'Bearer ' || v_secret
          );
  exception when others then
    raise log 'joumpa pd_sync_ping skipped on %: % (%)', tg_table_name, sqlerrm, sqlstate;
  end;
  return null;
end;
$_$;

revoke all on function private.pd_sync_ping() from public, anon, authenticated;

create trigger pd_settings_sync_ping
  after insert or update or delete or truncate on public.pd_settings
  for each statement execute function private.pd_sync_ping();
